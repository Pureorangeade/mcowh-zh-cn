'use strict';
const assert = require('node:assert/strict');
const {tokens,validateEdit,normalizeInput,parseRevision,restoreDraft,parseReviewDecisions}=require('../tools/editor/core.js');
const item={id:'test',source:'\\img[\\cself[5]]Hello <PLAYER> $tmp1!\r\nAgain',source_sha256:'hash',kind:'message'};
assert.deepEqual(tokens(item.source),['\\img[\\cself[5]]','<PLAYER>','$tmp1']);
const text='\\img[\\cself[5]]你好 <PLAYER> $tmp1！再见';
assert.equal(validateEdit(item,text),'');
assert.ok(validateEdit(item,text.replace('[5]','[6]')));
assert.ok(validateEdit(item,text+'\n@erase_save'));
assert.ok(validateEdit({...item,locked:true},text));
assert.equal(normalizeInput(item,'甲\n乙'),'甲\r\n乙');
assert.equal(normalizeInput({...item,kind:'choice'},'一 二\n三'),'一_二_三');
assert.ok(validateEdit({source:'Hello',kind:'image'},'你好\n再见'));
const byId=new Map([[item.id,item]]), payload={schema:1,project:'mcowh-zh',entries:[{id:'test',source_sha256:'hash',translation:text}]};
assert.equal(parseRevision(payload,byId).get('test'),text);
assert.throws(()=>parseRevision({...payload,entries:[...payload.entries,...payload.entries]},byId));
assert.throws(()=>parseRevision({...payload,entries:[null]},byId));
assert.throws(()=>parseRevision({...payload,entries:[{...payload.entries[0],source_sha256:'stale'}]},byId));
const unfinished={...payload,entries:[{...payload.entries[0],translation:'\\img['}]};
assert.throws(()=>parseRevision(unfinished,byId));
assert.equal(restoreDraft(unfinished,byId).get('test'),'\\img[');
const decision={id:'test',source_sha256:'hash',scope:'entry',status:'deferred_final',reason:'待查'};
assert.equal(parseReviewDecisions({...payload,review_decisions:[decision]},byId).size,1);
assert.throws(()=>parseRevision({...payload,review_decisions:[{...decision,source_sha256:'wrong'}]},byId));
assert.throws(()=>parseReviewDecisions({...payload,review_decisions:[decision,decision]},byId));
assert.throws(()=>parseReviewDecisions({...payload,review_decisions:[decision]},new Map([['test',{...item,locked:true}]])));
const command={id:'command',kind:'choice',source:'reset',source_sha256:'hash',locked:true,internal_command:true};
assert.ok(validateEdit(command,'重置'));
assert.equal(restoreDraft({schema:1,project:'mcowh-zh',entries:[{id:'command',source_sha256:'hash',translation:'重置'}]},new Map([['command',command]])).get('command'),'reset');
assert.equal(validateEdit({source:'Barrier num Layers'},'结界num层'),'');
assert.ok(validateEdit({source:'Acid Lvnum'},'强酸等级num'));
const menuItem={source:'Use, 500000\r\nShortcut, 400000\r\n',kind:'database'};
assert.equal(validateEdit(menuItem,'使用, 500000\r\n快捷栏, 400000\r\n'),'');
for(const bad of ['使用，500000\r\n快捷栏，400000\r\n','使用, 400000\r\n快捷栏, 500000\r\n','使用,500000\r\n快捷栏, 400000\r\n','使用, 500000\n快捷栏, 400000\n'])assert.ok(validateEdit(menuItem,bad));
assert.equal(validateEdit({source:'Cancel, 2\r\nContinue, -1'},'取消, 2\r\n继续, -1'),'');
assert.equal(validateEdit({source:'Use, if you need it.'},'需要时使用。'),'');
console.log('Editor core: control checks, imports, draft recovery and normalization passed.');
